#!/usr/bin/env node
// Emits src/pkjs/config/primitive-ids-generated.js: one PRIM_<NAME>: <value>
// entry per member of PrimitiveId (src/c/features/primitives/primitive_ids.h),
// with the exact integer value the C enum assigns it.
//
// Why this exists: Phase 3 (primitive value transport) needs PKJS to send
// numeric primitive IDs to the watch that mean the same thing there as
// PRIM_<NAME> means in primitive_ids.h. Hand-transcribing ~150 enum values
// into a JS file (some of which are `= OTHER_NAME` reassignments, not
// simple increments) is exactly the kind of thing that silently drifts the
// moment someone edits the C header and forgets the JS copy -- so, same
// reasoning as generate-message-keys.js: parse the one canonical source
// and generate the derived file, never hand-edit the derived file.
//
// Run this whenever primitive_ids.h changes (add/remove/reorder an entry,
// or move a `= OTHER_NAME` alias). Committing the generated file is fine,
// but it must be regenerated before relying on it if primitive_ids.h has
// moved since it was last written.
//
// Usage:
//   node scripts/generate-primitive-ids.js

var fs = require('fs');
var path = require('path');

var SRC = path.join(__dirname, '..', 'src', 'c', 'features', 'primitives', 'primitive_ids.h');
var OUT = path.join(__dirname, '..', 'src', 'pkjs', 'config', 'primitive-ids-generated.js');

var src = fs.readFileSync(SRC, 'utf8');

var enumStart = src.indexOf('typedef enum {');
var enumBodyStart = src.indexOf('{', enumStart) + 1;
var enumEnd = src.indexOf('} PrimitiveId;', enumBodyStart);
if (enumStart < 0 || enumEnd < 0) {
  throw new Error('Could not find "typedef enum { ... } PrimitiveId;" in ' + SRC);
}
var body = src.slice(enumBodyStart, enumEnd);

// Strip // line comments and /* */ block comments (primitive_ids.h uses
// only // comments today, but this is cheap insurance either way).
body = body.replace(/\/\*[\s\S]*?\*\//g, '');
body = body.replace(/\/\/.*$/gm, '');

var entries = body.split(',').map(function (s) { return s.trim(); }).filter(Boolean);

var values = {};
var order = [];
var next = 0;

entries.forEach(function (entry) {
  var eq = entry.indexOf('=');
  var name, valueExpr;
  if (eq >= 0) {
    name = entry.slice(0, eq).trim();
    valueExpr = entry.slice(eq + 1).trim();
  } else {
    name = entry.trim();
    valueExpr = null;
  }
  if (!/^[A-Z0-9_]+$/.test(name)) {
    throw new Error('Unexpected enum entry while parsing ' + SRC + ': "' + entry + '"');
  }
  var value;
  if (valueExpr === null) {
    value = next;
  } else if (/^-?\d+$/.test(valueExpr)) {
    value = parseInt(valueExpr, 10);
  } else if (Object.prototype.hasOwnProperty.call(values, valueExpr)) {
    value = values[valueExpr];
  } else {
    throw new Error('Enum entry "' + name + '" is assigned from unrecognized expression "' +
      valueExpr + '" -- generate-primitive-ids.js only understands integer literals and ' +
      'references to an earlier entry in the same enum.');
  }
  values[name] = value;
  order.push(name);
  next = value + 1;
});

var lines = order.map(function (name) { return '  ' + name + ': ' + values[name]; });

var out =
  '// GENERATED by scripts/generate-primitive-ids.js from\n' +
  '// src/c/features/primitives/primitive_ids.h -- do not hand-edit.\n' +
  '// Re-run that script after changing the C enum; see its own header\n' +
  '// comment for why this is generated rather than hand-written.\n' +
  'module.exports = {\n' +
  lines.join(',\n') +
  '\n};\n';

fs.writeFileSync(OUT, out);
console.log('Wrote ' + order.length + ' primitive ID values to ' + path.relative(process.cwd(), OUT));
