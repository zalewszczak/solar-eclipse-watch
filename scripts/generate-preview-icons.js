#!/usr/bin/env node
// Copies the small set of REAL icon PNGs the settings-page preview needs
// (resources/images/{simple,hollow,fullcolor}/<name>.png -- the very files
// package.json bundles for the watch) into one generated PKJS module,
// src/pkjs/data/generated/preview-icon-images.js, shaped as
//   { "<icons style id>": { "<icon name>": "data:image/png;base64,..." } }
// with style ids matching the "Icons style" setting: 0 simple, 1 hollow,
// 2 full color. The preview (config/config-preview.js) tints/outlines/scales
// them in the browser the same way the watch does, so this script only
// packages bytes -- no PNG decoder needed (no pngjs dependency).
//
// Which icons: exactly the ones the example features in the preview use.
// PREVIEW_ICON_TOKENS in config/preview-icons.js maps the "(token)" text the
// preview used to show -> icon file name; this script reads the same table,
// so adding an icon there and re-running this is all it takes.
//
// A missing PNG is not an error: that icon just keeps showing its "(text)"
// placeholder in the preview. Re-run after changing any source icon.
//
// Usage: node scripts/generate-preview-icons.js

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var SRC = path.join(ROOT, 'resources', 'images');
var OUT = path.join(ROOT, 'src', 'pkjs', 'data', 'generated', 'preview-icon-images.js');
var tokens = require(path.join(ROOT, 'src', 'pkjs', 'config', 'preview-icons.js')).PREVIEW_ICON_TOKENS;

var STYLE_DIRS = { '0': 'simple', '1': 'hollow', '2': 'fullcolor' };

var names = {};
Object.keys(tokens).forEach(function (t) { names[tokens[t]] = true; });
// Full color art has no ink channel, so its outline pass borrows the hollow
// silhouette (feature_icon_assets_draw_styled_with_outline) -- already covered
// because every name is embedded for all three styles.

var result = { '0': {}, '1': {}, '2': {} };
var found = 0, missing = [];
Object.keys(STYLE_DIRS).forEach(function (id) {
  Object.keys(names).forEach(function (name) {
    var file = path.join(SRC, STYLE_DIRS[id], name + '.png');
    if (!fs.existsSync(file)) { missing.push(STYLE_DIRS[id] + '/' + name + '.png'); return; }
    result[id][name] = 'data:image/png;base64,' + fs.readFileSync(file).toString('base64');
    found++;
  });
});

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT,
  '// GENERATED by scripts/generate-preview-icons.js -- do not edit by hand.\n' +
  'module.exports = ' + JSON.stringify(result) + ';\n');
console.log('generate-preview-icons: embedded ' + found + ' icon(s) into ' + path.relative(ROOT, OUT));
if (missing.length) console.log('generate-preview-icons: missing (preview keeps text placeholders): ' + missing.join(', '));
